/** Press shape for an action. The firmware rejects an empty state list. */
sealed class SwitchType(val code: Long) {
    object Toggle : SwitchType(0)
    object SwitchOnOff : SwitchType(1)
    object ToggleAndSwitch : SwitchType(2)

    /** Pre-action delay; the firmware supports 0, 0.5 and whole seconds 1 to 10. */
    class Delay(seconds: Double) : SwitchType(
        when {
            seconds < 0.75 -> 10
            seconds < 1.0 -> 21
            else -> 10L + seconds.toInt().coerceIn(1, 10)
        },
    )
}
