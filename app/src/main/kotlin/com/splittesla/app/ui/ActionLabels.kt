        DEV_TEST, OPEN_FRUNK, OPEN_TRUNK, PARK_BRAKE, SEAT_BELTS_WARNING, TRACK_MODE, AUTOPILOT_START,
        CRUISE_CONTROL_START, AUTOPILOT_EXTENDED, AUTOPILOT_SPEED_ADJUST, CHILD_UNLOCK, OPEN_DOOR,
        UNLOCK_CAR, TRACTION_CONTROL, SPEED_CONTROL, GEAR_SHIFT, SIMULATE_PARK, TRACK_MODE_STABILITY,
        TRACK_MODE_HANDLING, AUTOPILOT_MAX, DRIVER_MOVE_SEAT, PASSENGER_MOVE_SEAT, DISABLE_MOTOR,
        FRONT_LEFT_WINDOW, FRONT_RIGHT_WINDOW, REAR_LEFT_WINDOW, REAR_RIGHT_WINDOW,
    )
